import fs from "node:fs";
import path from "node:path";
import { parse } from "@babel/parser";
import { execFileSync } from "node:child_process";

// Fail before generating artifacts if a hand-maintained contract contains unresolved types.
execFileSync(process.execPath, ["node_modules/typescript/bin/tsc", "--noEmit", "--pretty", "false"], { stdio: "inherit" });

const manifest = JSON.parse(fs.readFileSync("src/component-manifest.json", "utf8"));
const rootExports = [], rootTypes = [], cleanExports = [], cleanTypes = [];
const names = new Set(), cleanNames = new Set();

for (const item of manifest) {
  const contract = fs.readFileSync(`src/contracts/${item.slug}.d.ts`, "utf8");
  if (/\bany\b|\[key:\s*string\]/.test(contract.replace(/\/\*[\s\S]*?\*\//g, ""))) throw new Error(`Unconstrained contract: ${item.slug}`);
  if (!contract.includes(`${item.primary}Props`)) throw new Error(`Missing Props contract: ${item.slug}`);
  for (const [variant, file] of [["classic", item.classic], ["clean", item.clean]]) {
    if (!file) continue;
    const clean = variant === "clean";
    const prefix = clean ? "../../../" : "../../";
    const target = `src/components/ui/${clean ? "clean/" : ""}${item.slug}`;
    const extras = item.exports.map(name => item.secondary?.[variant]?.[name]
      ? `export { ${item.secondary[variant][name]} as ${name} } from "${prefix}affectui-engine/${file}";`
      : `export const ${name} = ${item.primary};`).join("\n");
    const code = `// Generated by npm run build:tokens; edit the manifest or contracts instead.\nimport React from "react";\nimport DemoComponent, { __InnerComponent } from "${prefix}affectui-engine/${file}";\n${item.slug === "toaster" ? `export { toast } from "${prefix}affectui-engine/toaster-core.js";\n` : ""}
export function ${item.primary}({ demo = false, ...props } = {}) {
  return React.createElement(demo ? DemoComponent : __InnerComponent, props);
}
export const ${item.primary}Raw = __InnerComponent;
export const ${item.primary}Demo = DemoComponent;
${extras}
export default ${item.primary};\n`;
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(`${target}.js`, code);
    fs.writeFileSync(`${target}.d.ts`, `export * from "${prefix}contracts/${item.slug}.js";\nexport { default } from "${prefix}contracts/${item.slug}.js";\n`);
    const exported = [item.primary, `${item.primary}Raw`, `${item.primary}Demo`, ...item.exports, ...(item.slug === "toaster" ? ["toast"] : [])];
    const seen = clean ? cleanNames : names;
    const unique = exported.filter(n => !seen.has(n) && seen.add(n));
    (clean ? cleanExports : rootExports).push(`export { ${unique.join(", ")} } from "./components/ui/${clean ? "clean/" : ""}${item.slug}.js";`);
    (clean ? cleanTypes : rootTypes).push(`export { ${unique.join(", ")}, type ${item.primary}Props } from "./components/ui/${clean ? "clean/" : ""}${item.slug}.js";`);
  }
}
const context = 'export { ScreenFullContext, SCREEN_WIDTH } from "./affectui-engine/context.js";\n';
fs.writeFileSync("src/index.js", `${context}export { AFFECTUI_CATALOG, AFFECTUI_CATALOG as AETHERUI_CATALOG } from "./affectui-engine/catalog.js";\n${rootExports.join("\n")}\n`);
fs.writeFileSync("src/clean.js", `${context}${cleanExports.join("\n")}\n`);
const catalogTypes = `import * as React from "react";\nexport interface CatalogItem { slug: string; name: string; kind: "component" | "screen" | "block" | "illustration" | "motion"; category: string; description: string; isPro: boolean; loadClassic: () => Promise<unknown>; loadClean?: () => Promise<unknown>; loadSource?: () => Promise<string>; loadCleanSource?: () => Promise<string>; loadDocs?: () => Promise<unknown>; loadCleanDocs?: () => Promise<unknown>; }\nexport declare const AFFECTUI_CATALOG: CatalogItem[];\nexport declare const AETHERUI_CATALOG: typeof AFFECTUI_CATALOG;\nexport declare const ScreenFullContext: React.Context<boolean>;\nexport declare const SCREEN_WIDTH: number;\n`;
fs.writeFileSync("src/index.d.ts", catalogTypes + rootTypes.join("\n") + "\n");
fs.writeFileSync("src/clean.d.ts", 'export { ScreenFullContext, SCREEN_WIDTH } from "./index.js";\n' + cleanTypes.join("\n") + "\n");
// Replace only the source-text export; runtime named exports in these modules remain intact.
const catalog = fs.readFileSync("src/affectui-engine/catalog.js", "utf8");
for (const item of manifest) {
  const start = catalog.indexOf(`slug: "${item.slug}"`);
  const end = catalog.indexOf('\n  },', start);
  const entry = catalog.slice(start, end);
  for (const [variant, field] of [["classic", "loadSource"], ["clean", "loadCleanSource"]]) {
    const sourceFile = entry.match(new RegExp(`${field}:.*?import\\("\\./([^\"]+)"`))?.[1];
    if (!sourceFile) continue;
    const file = `src/affectui-engine/${sourceFile}`;
    const code = fs.readFileSync(file, "utf8");
    const ast = parse(code, { sourceType: "module" });
    const defaultExport = ast.program.body.flatMap(n => n.specifiers ?? []).find(n => n.exported?.name === "default");
    const name = defaultExport?.local.name;
    const variable = ast.program.body.flatMap(n => n.declarations ?? []).find(n => n.id.name === name);
    if (!["StringLiteral", "TemplateLiteral"].includes(variable?.init?.type)) throw new Error(`Missing source string: ${sourceFile}`);
    const clean = variant === "clean";
    const api = [item.primary, `${item.primary}Raw`, `${item.primary}Demo`, ...item.exports, ...(item.slug === "toaster" ? ["toast"] : [])];
    const text = `// Canonical component API. Install the package, or use the CLI for a complete standalone export.\nimport "@aether-ui/react/styles.css";\nexport { ${api.join(", ")}, type ${item.primary}Props } from "@aether-ui/react/ui/${clean ? "clean/" : ""}${item.slug}";\nexport { default } from "@aether-ui/react/ui/${clean ? "clean/" : ""}${item.slug}";\n`;
    fs.writeFileSync(file, code.slice(0, variable.init.start) + JSON.stringify(text) + code.slice(variable.init.end));
  }
}
console.log(`Generated ${manifest.length} Classic and ${manifest.filter(i => i.clean).length} Clean component APIs.`);
